import jsPDF from 'jspdf';
import { DeliverableOutput } from '../types';

export const exportService = {
  /**
   * Export single or multiple deliverables to a formatted PDF
   */
  exportToPdf(deliverables: DeliverableOutput[], sourceName: string) {
    const doc = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4'
    });

    // Title banner
    doc.setFillColor(15, 23, 42); // neutral-900
    doc.rect(0, 0, 210, 35, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.setTextColor(255, 255, 255);
    doc.text('GramX — Deliverables Export', 14, 16);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(148, 163, 184); // neutral-400
    doc.text(`Source Document: ${sourceName} | Team: GRAMX (SIH26154)`, 14, 25);
    doc.text(`Exported at: ${new Date().toLocaleString()} | Deliverables: ${deliverables.length}`, 14, 30);

    let yOffset = 45;

    deliverables.forEach((item, index) => {
      // Check if page overflow
      if (yOffset > 240) {
        doc.addPage();
        yOffset = 20;
      }

      // Deliverable header
      doc.setFillColor(241, 245, 249);
      doc.roundedRect(14, yOffset - 4, 182, 12, 2, 2, 'F');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(15, 23, 42);
      doc.text(`${index + 1}. [${item.category}] ${item.title}`, 18, yOffset + 4);

      yOffset += 16;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9.5);
      doc.setTextColor(51, 65, 85);

      const splitText = doc.splitTextToSize(item.contentEn, 178);
      
      splitText.forEach((line: string) => {
        if (yOffset > 275) {
          doc.addPage();
          yOffset = 20;
        }
        doc.text(line, 16, yOffset);
        yOffset += 5;
      });

      yOffset += 8;
    });

    // Save PDF
    const filename = `GramX_Export_${sourceName.replace('.pdf', '')}_${Date.now()}.pdf`;
    doc.save(filename);
  },

  /**
   * Export to DOCX formatted document
   */
  exportToDocx(deliverables: DeliverableOutput[], sourceName: string) {
    let content = `=======================================================\n`;
    content += `BHARATCONTENT AI — ENTERPRISE TRANSFORMATION EXPORT\n`;
    content += `Source Document: ${sourceName}\n`;
    content += `Team: GRAMX (SIH AI Content Engine)\n`;
    content += `Export Date: ${new Date().toLocaleString()}\n`;
    content += `=======================================================\n\n`;

    deliverables.forEach((item, i) => {
      content += `-------------------------------------------------------\n`;
      content += `${i + 1}. [${item.category}] ${item.title.toUpperCase()}\n`;
      content += `Status: ${item.status} | Version: ${item.version} | Review: ${item.reviewStatus}\n`;
      content += `-------------------------------------------------------\n\n`;
      content += `[ENGLISH VERSION]\n${item.contentEn}\n\n`;
      if (item.contentTe) {
        content += `[TELUGU LOCALIZATION]\n${item.contentTe}\n\n`;
      }
      if (item.structuredData?.presentation) {
        content += `[SLIDE BREAKDOWN]\n`;
        item.structuredData.presentation.slides.forEach(s => {
          content += `\nSlide ${s.slideNumber}: ${s.title}\n`;
          s.bullets.forEach(b => content += `  * ${b}\n`);
          content += `  Speaker Notes: ${s.speakerNotes}\n`;
        });
        content += `\n`;
      }
      if (item.structuredData?.videoPackage) {
        content += `[VIDEO SCRIPT & NARRATION]\n`;
        content += item.structuredData.videoPackage.script + `\n\n`;
      }
    });

    const blob = new Blob([content], { type: 'application/msword;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `GramX_${sourceName.replace('.pdf', '')}_Deliverables.docx`;
    link.click();
    URL.revokeObjectURL(url);
  },

  /**
   * Export Presentation slides to PPTX / Presentation text deck
   */
  exportToPptx(item: DeliverableOutput, sourceName: string) {
    const slides = item.structuredData?.presentation?.slides || [];
    let pptContent = `PRESENTATION DECK: ${item.title}\n`;
    pptContent += `Source: ${sourceName}\n`;
    pptContent += `Generated by GramX (GramX - SIH2026)\n\n`;

    slides.forEach(slide => {
      pptContent += `=== SLIDE ${slide.slideNumber}: ${slide.title} ===\n`;
      slide.bullets.forEach(bullet => {
        pptContent += `• ${bullet}\n`;
      });
      pptContent += `SPEAKER NOTES: ${slide.speakerNotes}\n\n`;
    });

    const blob = new Blob([pptContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Presentation_Deck_8_Slides_${sourceName.replace('.pdf', '')}.pptx`;
    link.click();
    URL.revokeObjectURL(url);
  },

  /**
   * Export Subtitles in standard .SRT format
   */
  exportToSrt(item: DeliverableOutput) {
    const srtContent = item.structuredData?.videoPackage?.subtitlesSrt || `1\n00:00:01,000 --> 00:00:05,000\nGramX Subtitles\n`;
    const blob = new Blob([srtContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Subtitles_Dual_Track.srt`;
    link.click();
    URL.revokeObjectURL(url);
  },

  /**
   * Copy to clipboard helper
   */
  async copyToClipboard(text: string): Promise<boolean> {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      return false;
    }
  }
};
